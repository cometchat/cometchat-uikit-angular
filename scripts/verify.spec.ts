// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { closestBase, relatedInputs, touchesLibrary } from './verify.mjs';
import { foreignHooks } from './install-hooks-auto.mjs';

describe('verify', () => {
  describe('closestBase', () => {
    it('picks the branch HEAD is fewest commits ahead of', () => {
      expect(
        closestBase([
          { ref: 'origin/ci-sandbox-v5', ahead: 2 },
          { ref: 'origin/dev-v5', ahead: 58 },
          { ref: 'origin/master-v5', ahead: 140 },
        ])
      ).toBe('origin/ci-sandbox-v5');
    });

    it('skips refs that do not exist locally, and returns null when none do', () => {
      expect(closestBase([{ ref: 'origin/ci-sandbox-v5', ahead: null }, { ref: 'origin/dev-v5', ahead: 3 }])).toBe('origin/dev-v5');
      expect(closestBase([{ ref: 'origin/dev-v5', ahead: null }])).toBeNull();
    });
  });

  describe('relatedInputs', () => {
    const lib = 'projects/cometchat-uikit/src/lib/components/x/x.component';

    it('passes changed source and spec files under the test roots', () => {
      expect(
        relatedInputs([`${lib}.ts`, `${lib}.spec.ts`, 'scripts/ci/ci-gate.mjs', '.storybook/__tests__/a.spec.ts'], () => false)
      ).toEqual(['.storybook/__tests__/a.spec.ts', `${lib}.spec.ts`, `${lib}.ts`, 'scripts/ci/ci-gate.mjs']);
    });

    it('maps a changed template or stylesheet to its component class when that exists', () => {
      const exists = (p: string) => p === `${lib}.ts`;
      expect(relatedInputs([`${lib}.html`, `${lib}.css`], exists)).toEqual([`${lib}.ts`]);
      expect(relatedInputs(['projects/cometchat-uikit/src/styles/theme.css'], exists)).toEqual([]);
    });

    it('ignores files no unit test can import: docs, e2e, stories, type declarations, config', () => {
      expect(
        relatedInputs(
          ['docs/guide.mdx', 'e2e/smoke.spec.ts', `${lib}.stories.ts`, 'projects/cometchat-uikit/src/types.d.ts', 'package.json', '.github/workflows/pr-gate.yml'],
          () => true
        )
      ).toEqual([]);
    });
  });

  describe('touchesLibrary', () => {
    it('is true for library source and for dependency or build config', () => {
      expect(touchesLibrary(['projects/cometchat-uikit/src/lib/a.ts'])).toBe(true);
      expect(touchesLibrary(['projects/cometchat-uikit/src/lib/a.html'])).toBe(true);
      expect(touchesLibrary(['package-lock.json'])).toBe(true);
      expect(touchesLibrary(['angular.json'])).toBe(true);
    });

    it('is false for library specs, the sample app, E2E, docs and scripts', () => {
      expect(
        touchesLibrary(['projects/cometchat-uikit/src/lib/a.spec.ts', 'projects/sample-app/src/main.ts', 'e2e/a.spec.ts', 'docs/a.mdx', 'scripts/verify.mjs'])
      ).toBe(false);
    });
  });
});

describe('install-hooks-auto: foreignHooks', () => {
  const ours = '#!/usr/bin/env bash\n# Auto-generated by scripts/install-hooks.sh — do not edit directly.\n';
  const files = (map: Record<string, string>) => (p: string) => map[p.split('/').pop() as string] ?? null;

  it('is empty when no hooks exist, or only ours do, so the install goes ahead', () => {
    expect(foreignHooks('.git/hooks', files({}))).toEqual([]);
    expect(foreignHooks('.git/hooks', files({ 'pre-commit': ours, 'pre-push': ours }))).toEqual([]);
  });

  it("names a developer's own hook, so the install leaves it in place", () => {
    expect(foreignHooks('.git/hooks', files({ 'pre-commit': ours, 'pre-push': '#!/bin/sh\nmy-own-check\n' }))).toEqual(['pre-push']);
  });
});
