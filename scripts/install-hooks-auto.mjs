#!/usr/bin/env node
// Runs on npm install / npm ci (the `prepare` script): installs this repo's git hooks
// (scripts/install-hooks.sh) so the pre-push verify runs for everyone without a separate step.
// Never fails the install. Does nothing in CI, outside a git checkout, without bash, or when a
// pre-commit or pre-push hook that this repo did not write is already there (it says so).
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const MARK = 'Auto-generated by scripts/install-hooks.sh';

export function foreignHooks(hooksDir, read = (p) => (existsSync(p) ? readFileSync(p, 'utf8') : null)) {
  return ['pre-commit', 'pre-push'].filter((h) => {
    const text = read(join(hooksDir, h));
    return text != null && !text.includes(MARK);
  });
}

function main() {
  if (process.env.CI) return;
  let hooksDir;
  try {
    hooksDir = execFileSync('git', ['rev-parse', '--git-common-dir'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return;
  }
  const foreign = foreignHooks(join(hooksDir, 'hooks'));
  if (foreign.length) {
    console.log(`install-hooks: leaving your own ${foreign.join(' and ')} hook in place. To use this repo's checks instead: npm run hooks:install`);
    return;
  }
  try {
    execFileSync('bash', ['scripts/install-hooks.sh'], { stdio: 'inherit' });
  } catch {
    console.log('install-hooks: could not install the git hooks (is bash available?). Run npm run verify before pushing.');
  }
}

if (import.meta.url === `file://${process.argv[1]}`) main();
