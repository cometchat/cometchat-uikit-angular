#!/usr/bin/env bash
# =============================================================================
# Installs git hooks for this repository.
# Runs on npm install (via scripts/install-hooks-auto.mjs) or by hand: npm run hooks:install
# =============================================================================

set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
# Works in worktrees too: hooks live in the common git dir.
HOOKS_DIR="$(git rev-parse --git-common-dir)/hooks"
SCRIPTS_DIR="$REPO_ROOT/scripts"

echo "Installing git hooks..."

# pre-commit
cat > "$HOOKS_DIR/pre-commit" << 'HOOK'
#!/usr/bin/env bash
# Auto-generated by scripts/install-hooks.sh — do not edit directly.
# Edit scripts/pre-commit-checks.sh instead.
REPO_ROOT="$(git rev-parse --show-toplevel)"
# A branch from before the hooks existed has no checks to run.
[ -x "$REPO_ROOT/scripts/pre-commit-checks.sh" ] || exit 0
exec "$REPO_ROOT/scripts/pre-commit-checks.sh"
HOOK

# pre-push: the quick local verify (scripts/verify.mjs)
cat > "$HOOKS_DIR/pre-push" << 'HOOK'
#!/usr/bin/env bash
# Auto-generated by scripts/install-hooks.sh — do not edit directly.
# Edit scripts/pre-push-checks.sh instead.
REPO_ROOT="$(git rev-parse --show-toplevel)"
# A branch from before the hooks existed has no checks to run.
[ -x "$REPO_ROOT/scripts/pre-push-checks.sh" ] || exit 0
exec "$REPO_ROOT/scripts/pre-push-checks.sh"
HOOK

chmod +x "$HOOKS_DIR/pre-commit" "$HOOKS_DIR/pre-push"
chmod +x "$SCRIPTS_DIR/pre-commit-checks.sh" "$SCRIPTS_DIR/pre-push-checks.sh"

echo "✓ pre-commit hook installed (credentials, debugger, effect(), console.log, .env, lint, secrets)"
echo "✓ pre-push hook installed (npm run verify: lint, type check, related unit tests, library build)"
echo ""
echo "The hooks run on every 'git commit' and 'git push'. CI runs the same checks and decides."
echo "To bypass in an emergency: --no-verify"
